class TestManifest(unittest.TestCase):
    def test_parse_date(self):
        self.assertEqual(census.parse_date("2026/11/09"), "2026-11-09")
        self.assertEqual(census.parse_date("2025/3/14"), "2025-03-14")
        self.assertEqual(census.parse_date("2025-03-14"), "2025-03-14")
        self.assertEqual(census.parse_date("03/14/2025"), "2025-03-14")
        self.assertEqual(census.parse_date(" 2025/3/14 00:00:00"), "2025-03-14")
        for bad in ("", None, "2025/13/01", "2025/02/30", "March 2025"):
            self.assertIsNone(census.parse_date(bad))

    def test_parse_manifest(self):
        rows, st = census.parse_manifest(NONPREC.encode("utf-8"), census.MAIN_MANIFESTS[0])
        self.assertEqual(len(rows), 5)
        self.assertEqual((st["no_file_name"], st["bad_date"]), (1, 1))
        self.assertEqual((st["earliest"], st["latest"]), ("2014-04-28", "2026-11-09"))
        self.assertEqual(st["document_type"], "NON-PRECEDENTIAL")
        r = rows[0]
        self.assertEqual((r["collection"], r["date"], r["docket"], r["agency"]),
                         ("nonprecedential", "2026-11-09", "DA-3330-25-1121-I-1", "Department of the Army"))
        self.assertEqual(r["row_id"], census.row_id("nonprecedential", "Moreland_Todd_DA-3330-25-1121-I-1_4200901.pdf"))

    def test_parse_manifest_bom_and_unpadded(self):
        rows, st = census.parse_manifest(b"\xef\xbb\xbf" + PREC.encode("utf-8"), census.MAIN_MANIFESTS[1])
        self.assertEqual([r["date"] for r in rows], ["2026-10-22", "2025-11-25", "2025-03-14", "2022-03-24"])
        self.assertEqual({r["collection"] for r in rows}, {"precedential"})

    def test_row_id(self):
        a = census.row_id("nonprecedential", "Moreland_Todd_X.pdf")
        self.assertEqual(a, census.row_id("nonprecedential", " moreland_todd_x.PDF "))
        self.assertNotEqual(a, census.row_id("precedential", "Moreland_Todd_X.pdf"))
        self.assertEqual(len(a), 12)

    def test_pdf_url(self):
        self.assertEqual(census.pdf_url("precedential", "Shows_MichelleDC-0752-22-0160-I-3__Opinion and Order.pdf"),
                         "https://www.mspb.gov/decisions/precedential/Shows_MichelleDC-0752-22-0160-I-3__Opinion%20and%20Order.pdf")
        self.assertEqual(census.pdf_url("nonprecedential", "Moreland_Todd_DA-3330-25-1121-I-1_4200901.pdf"),
                         "https://www.mspb.gov/decisions/nonprecedential/Moreland_Todd_DA-3330-25-1121-I-1_4200901.pdf")

    def test_merge_dedupes_across_manifests(self):
        frame = {}
        rows, _ = census.parse_manifest(NONPREC, census.MAIN_MANIFESTS[0])
        self.assertEqual(census.merge(frame, rows, census.MAIN_MANIFESTS[0]), 3)
        rows, _ = census.parse_manifest(PREC, census.MAIN_MANIFESTS[1])
        self.assertEqual(census.merge(frame, rows, census.MAIN_MANIFESTS[1]), 3)
        rows, _ = census.parse_manifest(TABLE, census.EXTRA_MANIFESTS[0])
        self.assertEqual(census.merge(frame, rows, census.EXTRA_MANIFESTS[0]), 1)
        self.assertEqual(len(frame), 6)
        mor = frame[census.row_id("nonprecedential", "Moreland_Todd_DA-3330-25-1121-I-1_4200901.pdf")]
        self.assertEqual(mor["manifests"], [census.MAIN_MANIFESTS[0], census.EXTRA_MANIFESTS[0]])
        self.assertEqual(mor["file_name"], "Moreland_Todd_DA-3330-25-1121-I-1_4200901.pdf")


class TestClassify(unittest.TestCase):
    def test_fake_and_ai(self):
        r = census.classify(FAKE_AI)
        self.assertTrue(r["fake_cite"] and r["ai_mention"] and r["ai_citation"] and r["pro_se"])
        self.assertEqual(r["kind"], "final")
        self.assertFalse(r["action"])
        self.assertIn("fake_cite", r["excerpts"])

    def test_fake_phrases(self):
        for s in ("He relies on fictitious case citations.",
                  "The Board decisions cited by the appellant do not appear to exist.",
                  "We were unable to locate the cases cited in his petition.",
                  "The petition quotes non- existent cases.",
                  "These authorities did not exist."):
            self.assertTrue(census.classify(s)["fake_cite"], s)

    def test_not_fake(self):
        for s in ("The appellant alleges the agency fabricated a case against him and fabricated its decision.",
                  "We find no authority for that proposition, and the cases the appellant cites are inapposite.",
                  "The appellant submitted fake medical documentation",
                  "The appellant, Mr. Al-Hakim, filed a petition."):
            r = census.classify(s)
            self.assertFalse(r["fake_cite"], s)
            self.assertFalse(r["ai_mention"], s)

    def test_ai_terms(self):
        for s in ("an AI-generated brief", "an Al-generated brief", "a tool (AI) was used", "using ChatGPT",
                  "a large language model", "generative AI"):
            self.assertTrue(census.classify(s)["ai_mention"], s)

    def test_kind_and_pro_se_in_head_only(self):
        self.assertEqual(census.classify("THIS ORDER IS NONPRECEDENTIAL REMAND ORDER")["kind"], "remand")
        self.assertEqual(census.classify("2026 MSPB 10 OPINION AND ORDER")["kind"], "opinion")
        self.assertEqual(census.classify("ORDER ON STAY REQUEST")["kind"], "other_order")
        self.assertEqual(census.classify("nothing here")["kind"], "unknown")
        late = "x " * 2500 + "the appellant, who is pro se"
        self.assertFalse(census.classify(late)["pro_se"])
        self.assertTrue(census.classify(PLAIN)["pro_se"])

    def test_action_only_with_fake(self):
        self.assertTrue(census.classify(FAKE_AI + " See 5 C.F.R. § 1201.43.")["action"])
        self.assertFalse(census.classify(PLAIN + " The Board may impose sanctions.")["action"])


def make_docs():
    docs = []

    def add(n, date, fake=False, pro_se=False, ai=False, action=False, kind="final"):
        for _ in range(n):
            docs.append({"row_id": "r%04d" % len(docs), "collection": "nonprecedential", "docket": "X",
                         "date": date, "agency": "A", "doc_status": "ok", "readable": True, "chars": 5000,
                         "kind": kind, "fake_cite": fake, "pro_se": pro_se, "ai_mention": ai,
                         "ai_citation": ai and fake, "action": action, "file_name": "Name_%d.pdf" % len(docs)})
    add(150, "2024-06-01")
    add(1, "2025-01-10", fake=True, pro_se=True)
    add(100, "2026-01-01")
    add(50, "2026-01-01", pro_se=True)
    add(1, "2026-02-01", fake=True, pro_se=True, ai=True)
    add(1, "2026-02-01", fake=True, pro_se=True, action=True)
    add(1, "2026-02-01", fake=True, pro_se=True, kind="remand")
    add(1, "2026-02-01", fake=True)
    for _ in range(2):
        docs.append({"row_id": "u%d" % len(docs), "collection": "nonprecedential", "date": "2026-03-01",
                     "doc_status": "pdf_http_404", "readable": False, "file_name": "Gone.pdf"})
    return docs


class TestGrade(unittest.TestCase):
    def test_all_held(self):
        res = census.grade(make_docs(), {"court_rows": [], "review_rows": [{"case_id": "1"}]}, [])
        v = {k: p["verdict"] for k, p in res["predictions"].items()}
        self.assertEqual(v, {"P1": "held", "P2": "held", "P3": "held", "P4": "held", "P5": "held",
                             "P6": "held", "P7": "held", "P8": "held"})
        c = res["counts"]
        self.assertEqual((c["in_frame"], c["readable"], c["fake_cite"], c["pro_se_readable"]), (307, 305, 5, 54))
        self.assertEqual(c["fetch_status"], {"ok": 305, "pdf_http_404": 2})
        self.assertEqual(c["by_year"]["2025"], {"readable": 1, "fake_cite": 1, "ai_mention": 0, "ai_citation": 0})
        self.assertEqual(res["predictions"]["P3"]["detail"]["early"], {"n": 151, "k": 1, "share": 0.007})
        self.assertEqual(res["predictions"]["P3"]["detail"]["late"], {"n": 154, "k": 4, "share": 0.026})
        self.assertEqual(len(res["fake_cite_decisions"]), 5)
        self.assertNotIn("file_name", res["fake_cite_decisions"][0])

    def test_failed_and_not_testable(self):
        docs = [d for d in make_docs() if not (d.get("fake_cite") and d["date"] == "2025-01-10")]
        res = census.grade(docs, None, [])
        self.assertEqual(res["predictions"]["P1"]["verdict"], "failed")
        self.assertEqual(res["predictions"]["P8"]["verdict"], "not testable")
        res = census.grade(make_docs(), {"court_rows": [{"case_id": "9"}], "review_rows": []}, [])
        self.assertEqual(res["predictions"]["P8"]["verdict"], "failed")
        res = census.grade([d for d in make_docs() if not d.get("fake_cite")], None, [])
        for k in ("P2", "P3", "P4", "P5", "P6", "P7"):
            self.assertEqual(res["predictions"][k]["verdict"], "not testable", k)

    def test_outputs_never_carry_file_names(self):
        docs = make_docs()
        res = census.grade(docs, None, [{"manifest": "m", "rows": 1, "in_window": 1}])
        out = census.rows_csv(docs) + census.results_md(res, {}) + json.dumps(res, default=str)
        self.assertNotIn("Name_", out)
        self.assertNotIn("Gone.pdf", out)
        self.assertTrue(census.rows_csv(docs).startswith(",".join(census.ROW_COLS) + "\n"))


