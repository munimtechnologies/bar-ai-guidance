def listing_fetch(url):
    return PAGES_L[int(url.rsplit("=", 1)[1])]


class Parsing(unittest.TestCase):
    def test_rows(self):
        got = census.parse_rows(PAGES_L[0])
        self.assertEqual([r["key"] for r in got], ["375-68", "375-65", "375-31"])
        self.assertEqual(got[1]["date"], "2026-10-30")
        self.assertEqual(got[1]["doc"], doc_id("a65"))
        self.assertEqual(got[1]["case"], "05-CA-328932")
        self.assertEqual(got[1]["name"], "Pepperjacks, LLC d/b/a Notch 8 Brewery")
        self.assertEqual(got[2]["name"], "American Backflow & Fire Prevention, Inc.")
        self.assertEqual((got[2]["volume"], got[2]["slip"]), (375, 31))
        p1 = census.parse_rows(PAGES_L[1].decode("utf-8"))
        self.assertEqual(p1[2]["date"], "2024-03-05")
        self.assertFalse(census.page_done(p1))
        self.assertTrue(census.page_done(census.parse_rows(PAGES_L[2])))
        self.assertTrue(census.page_done([]))
        self.assertEqual(census.parse_rows(b"<html>no table</html>"), [])

    def test_window_and_urls(self):
        self.assertTrue(census.in_window({"date": "2024-01-01"}))
        self.assertFalse(census.in_window({"date": "2023-12-31"}))
        self.assertFalse(census.in_window({"date": None}))
        self.assertEqual(census.listing_url(3), census.LISTING % 3)
        self.assertEqual(census.mirror_url(doc_id("a65")), "https://nlrbresearch.com/pdfs/%s.pdf" % doc_id("a65"))
        self.assertEqual(census.mirror_url("../etc/passwd"), "")
        self.assertEqual(census.mirror_url(None), "")


class Classify(unittest.TestCase):
    def test_rivas_needs_nlrb_clause(self):
        r = census.classify(TEXT_RIVAS)
        self.assertEqual((r["fake_cite"], r["fake_series"], r["fake_nlrb"], r["ai_mention"], r["referral"]),
                         (True, False, True, False, False))
        self.assertIn("fake_cite", r["excerpts"])

    def test_pepperjacks(self):
        r = census.classify(TEXT_PEPPER)
        self.assertEqual((r["fake_cite"], r["fake_series"], r["backflow"], r["pro_se"], r["ai_mention"],
                          r["referral"], r["ghost"]), (True, True, True, True, False, False, False))

    def test_backflow(self):
        r = census.classify(TEXT_BACKFLOW)
        self.assertEqual((r["fake_cite"], r["fake_series"], r["ai_mention"], r["ai_citation"], r["referral"],
                          r["ghost"], r["backflow"], r["hallucination"]),
                         (True, True, True, True, True, True, False, False))

    def test_plain_and_hyphens(self):
        r = census.classify(TEXT_PLAIN)
        self.assertFalse(any(r[k] for k in census.FLAG_KEYS))
        self.assertTrue(census.classify("The brief relied on fabri- cated cases.")["fake_cite"])
        self.assertEqual(census.variants("a  b"), ["a b"])
        r = census.classify("")
        self.assertEqual(r["chars"], 0)
        self.assertFalse(any(r[k] for k in census.FLAG_KEYS))


class Database(unittest.TestCase):
    def test_rows(self):
        self.assertEqual(len(census.db_check(CSV_PLAIN)["nlrb_rows"]), 0)
        self.assertEqual(len(census.db_check(CSV_PLAIN)["joined"]), 1)
        self.assertEqual(len(census.db_check(CSV_NLRB)["nlrb_rows"]), 1)
        self.assertEqual(len(census.db_check(CSV_CITE)["nlrb_rows"]), 0)

    def test_tokens(self):
        self.assertEqual(census.name_tokens("American Backflow & Fire Prevention, Inc."), ["Backflow", "Prevention"])
        self.assertEqual(census.name_tokens("Pepperjacks, LLC d/b/a Notch 8 Brewery"),
                         ["Pepperjacks", "Notch", "Brewery"])

    def test_in_db(self):
        bf = {"volume": 375, "slip": 31, "name": "American Backflow & Fire Prevention, Inc."}
        pj = {"volume": 375, "slip": 65, "name": "Pepperjacks, LLC d/b/a Notch 8 Brewery"}
        other = {"volume": 375, "slip": 6, "name": "X"}
        self.assertTrue(census.in_db(census.db_check(CSV_NLRB), bf))
        self.assertFalse(census.in_db(census.db_check(CSV_NLRB), pj))
        self.assertTrue(census.in_db(census.db_check(CSV_CITE), pj))
        self.assertFalse(census.in_db(census.db_check(CSV_CITE), other))
        self.assertFalse(census.in_db(census.db_check(CSV_PLAIN), bf))
        self.assertFalse(census.in_db(None, bf))


class Frame(unittest.TestCase):
    def setUp(self):
        self.p = mock.patch.object(run_job, "DELAY_S", 0)
        self.p.start()

    def tearDown(self):
        self.p.stop()

    def test_three_pages(self):
        seen = []

        def fetch(url):
            seen.append(url)
            return listing_fetch(url)
        docs, info, failed = run_job.build_frame([], fetch)
        self.assertEqual((failed, len(seen), info["pages"], info["complete"]), (0, 3, 3, True))
        self.assertEqual([d["key"] for d in docs], ["375-68", "375-65", "375-31", "374-30", "373-40"])
        self.assertEqual((info["rows_read"], info["same_citation_skipped"], info["in_frame"], info["outside_window"]),
                         (8, 1, 5, 2))
        self.assertEqual((info["known_in_frame"], info["no_doc_in_frame"], info["no_case_in_frame"]), (3, 0, 0))
        self.assertEqual(info["in_frame_by_year"], {"2024": 1, "2026": 4})
        self.assertEqual(info["in_frame_by_volume"], {"373": 1, "374": 1, "375": 3})

    def test_incomplete_and_failures(self):
        docs, info, failed = run_job.build_frame([], lambda u: PAGES_L[0])
        self.assertEqual((failed, len(docs), info["pages"], info["complete"]), (0, 3, run_job.MAX_PAGES, False))

        def boom(url):
            raise OSError("down")
        docs, info, failed = run_job.build_frame([], boom)
        self.assertEqual((docs, failed), ([], 1))
        self.assertIn("error", info)
        docs, info, failed = run_job.build_frame([], lambda u: b"<html></html>")
        self.assertEqual((docs, failed), ([], 1))


