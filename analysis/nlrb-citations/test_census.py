class Job(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def fake_get(self, url, tries=3, timeout=120, accept="*/*"):
        if url == run_job.CSV_URL:
            return CSV_NLRB.encode("utf-8"), "text/csv"
        if url.startswith("https://www.nlrb.gov/"):
            return listing_fetch(url), "text/html"
        if url.startswith("https://nlrbresearch.com/pdfs/"):
            return b"%PDF-" + url.encode("utf-8"), "application/pdf"
        raise urllib.error.HTTPError(url, 404, "not found", {}, None)

    @staticmethod
    def fake_text(data):
        if doc_id("a65").encode("utf-8") in data:
            return 3, TEXT_PEPPER
        if doc_id("a31").encode("utf-8") in data:
            return 2, TEXT_BACKFLOW
        if doc_id("b30").encode("utf-8") in data:
            return 1, TEXT_RIVAS
        return 4, TEXT_PLAIN

    def run_main(self, extra=()):
        ps = [mock.patch.object(run_job, "DELAY_S", 0),
              mock.patch.object(run_job, "get_retry", self.fake_get),
              mock.patch.object(run_job, "pdf_text", self.fake_text),
              mock.patch.object(run_job, "wait_for_plan", lambda m, s: ({"sha": "a"}, {"sha": "b"}, s))] + list(extra)
        for p in ps:
            p.start()
        try:
            return run_job.main(["--out-dir", self.tmp])
        finally:
            for p in reversed(ps):
                p.stop()

    def test_main(self):
        rc = self.run_main([mock.patch.object(census, "MIN_FRAME", 1)])
        self.assertEqual(rc, 0)
        with open(os.path.join(self.tmp, "results.json"), encoding="utf-8") as fh:
            body = fh.read()
        res = json.loads(body)
        v = {k: x["verdict"] for k, x in res["predictions"].items()}
        self.assertEqual(v, {"P1": "held", "P2": "failed", "P3": "held", "P4": "held", "P5": "held",
                             "P6": "failed", "P7": "held", "P8": "held"})
        self.assertEqual(res["predictions"]["P5"]["detail"]["missing"], ["374-30", "375-65"])
        self.assertEqual(res["predictions"]["P6"]["detail"]["decisions"], ["375-65"])
        c = res["counts"]
        self.assertEqual((c["in_frame"], c["readable"], c["fake_cite"], c["fake_series_only_patterns"],
                          c["fake_nlrb_clause_only"]), (5, 5, 3, 2, 1))
        self.assertEqual((c["ai_mention"], c["referral"], c["ghost"], c["backflow"], c["pro_se_among_fake"]),
                         (1, 1, 1, 1, 1))
        for name in ("Blick", "Acme", "Notch"):
            self.assertNotIn(name, body)
        with open(os.path.join(self.tmp, "rows.csv"), encoding="utf-8") as fh:
            rows = fh.read()
        self.assertEqual(len(rows.splitlines()), 6)
        for name in ("Pepperjacks", "Rivas", "Blick", "Acme"):
            self.assertNotIn(name, rows)
        self.assertEqual(sorted(os.listdir(os.path.join(self.tmp, "private", "texts"))),
                         ["374-30.txt", "375-31.txt", "375-65.txt"])
        self.assertTrue(os.path.exists(os.path.join(self.tmp, "private", "excerpts.txt")))
        with open(os.path.join(self.tmp, "results.md"), encoding="utf-8") as fh:
            self.assertIn("| 375 NLRB No. 65 | 2026-10-30 | 05-CA-328932 | False |", fh.read())

    def test_main_stops_small_frame(self):
        self.assertEqual(self.run_main(), 6)
        self.assertFalse(os.path.exists(os.path.join(self.tmp, "results.json")))


