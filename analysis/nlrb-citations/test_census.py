def doc_id(tag):
    return "0000000000000" + tag


def row(date, cite, tag, name, case):
    return ('<tr>\n  <td> %s </td>\n  <td>%s</td>\n  <td>\n    <a href="https://apps.nlrb.gov/link/document.aspx/%s">'
            '%s</a>\n  </td>\n  <td>\n    <a href="/case/%s">%s</a>\n  </td>\n</tr>\n') % (
        date, cite, doc_id(tag), name, case, case)


def page(rows):
    return ("<html><body><table><thead><tr><th>Date</th><th>Citation</th></tr></thead><tbody>%s</tbody></table>"
            "</body></html>" % "".join(rows)).encode("utf-8")


