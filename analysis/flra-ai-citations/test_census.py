BORROW = ("Background. " + "x " * 100 + "it appears that the Agency may have used a generative "
          "artificial-intelligence (Al) tool in drafting its brief. Nine citations are entirely fictitious. "
          "See Am. Backflow, 375 NLRB No. 31 (2026); Guidance, 89 Fed. Reg. 25609.")
OWN = ("The exceptions cite decisions that do not exist, apparently generated by artificial intelligence. "
       "Under 5 C.F.R. § 2429.5 we do not consider new arguments. We impose no sanction.")
REFER = ("The brief contains ghost citations produced with ChatGPT. We refer this matter to the "
         "Investigating Officer.")


class TestDates(unittest.TestCase):
    def test_formats(self):
        self.assertEqual(census.parse_date("10/30/2026"), "2026-10-30")
        self.assertEqual(census.parse_date("Issued Oct. 30, 2026"), "2026-10-30")
        self.assertEqual(census.parse_date("September 8, 2026"), "2026-09-08")
        self.assertEqual(census.parse_date("Jan. 08, 2025"), "2025-01-08")
        self.assertEqual(census.parse_date("2026-11-06"), "2026-11-06")
        self.assertIsNone(census.parse_date("no date here"))

    def test_window(self):
        self.assertTrue(census.in_window("2022-01-01"))
        self.assertFalse(census.in_window("2021-12-31"))
        self.assertFalse(census.in_window(None))


class TestListing(unittest.TestCase):
    def test_version(self):
        self.assertEqual(census.VERSION, "1.0.1")

    def test_flra(self):
        rows = census.parse_flra_listing(FLRA_HTML)
        self.assertEqual([r["citation"] for r in rows], ["74 FLRA No. 89", "74 FLRA No. 87"])
        self.assertEqual(rows[0]["date"], "2026-10-30")
        self.assertEqual(rows[0]["reporter_cite"], "74 FLRA 660")
        self.assertEqual(rows[0]["url"], "https://www.flra.gov/decisions/v74/74-89")
        self.assertEqual(rows[1]["date"], "2026-10-21")

    def test_two_row_layout(self):
        rows = census.parse_flra_listing(DRUPAL_HTML)
        self.assertEqual([r["citation"] for r in rows], ["74 FLRA No. 89", "74 FLRA No. 29", "72 FLRA No. 78"])
        self.assertEqual([r["date"] for r in rows], ["2026-10-30", "2025-01-08", "2021-07-01"])
        self.assertEqual([r["reporter_cite"] for r in rows], ["74 FLRA 660", "74 FLRA 181", "72 FLRA 414"])
        self.assertEqual(rows[0]["url"], "https://www.flra.gov/decisions/v74/74-89")
        self.assertEqual(rows[1]["url"], "https://www.flra.gov/decisions/v74/74-29.html")
        self.assertIsNone(rows[2]["url"])

    def test_header_only_page(self):
        self.assertEqual(census.parse_flra_listing("<table><tr><th>Citation #</th></tr><tr><td>none</td></tr></table>"), [])

    def test_fallback_without_table(self):
        page = ('<div>74 FLRA 640 Oct. 21, 2026 <a href="/decisions/v74/74-87">HTML</a></div>'
                '<div>74 FLRA 600 Oct. 1, 2026 <a href="/decisions/v74/74-80">HTML</a></div>')
        rows = census.parse_flra_listing(page)
        self.assertEqual([r["number"] for r in rows], [87, 80])
        self.assertEqual(rows[0]["date"], "2026-10-21")


class TestClassify(unittest.TestCase):
    def test_borrowing(self):
        r = census.classify(BORROW)
        self.assertTrue(r["ai_mention"])
        self.assertTrue(r["ai_citation"])
        self.assertTrue(r["other_body"])
        self.assertFalse(r["own_rule"])
        self.assertFalse(r["action"])
        self.assertIn("ai_citation", r["excerpts"])

    def test_own_rule_no_sanction(self):
        r = census.classify(OWN)
        self.assertTrue(r["ai_citation"])
        self.assertTrue(r["own_rule"])
        self.assertFalse(r["action"])
        self.assertFalse(r["other_body"])

    def test_referral(self):
        r = census.classify(REFER)
        self.assertTrue(r["ai_citation"])
        self.assertTrue(r["action"])
        self.assertFalse(r["mata"])

    def test_negatives(self):
        r = census.classify("The office moved to Birmingham (AL). The fictitious grievance was denied.")
        self.assertFalse(r["ai_mention"])
        self.assertFalse(r["ai_citation"])
        r = census.classify("The agency announced an artificial intelligence pilot for payroll.")
        self.assertTrue(r["ai_mention"])
        self.assertFalse(r["ai_citation"])
        self.assertFalse(r["other_body"])

    def test_main_text_drops_boilerplate(self):
        page = ("<html><body><nav>Artificial Intelligence</nav><main><p>Decision text</p></main>"
                "<footer>AI Use Cases</footer></body></html>")
        self.assertEqual(census.main_text(page), "Decision text")


class TestCoverage(unittest.TestCase):
    def test_db_rows_and_match(self):
        csv_text = ("case_id,Case Name,Court,State(s),Date\n"
                    "1,A v B,NLRB,USA,2026-08-25\n"
                    "2,C v FLRA,D.C. Circuit,USA,2026-10-20\n"
                    "3,HHS and NTEU,Federal Labor Relations Authority,USA,2026-10-21\n")
        db = census.db_rows(csv_text)
        self.assertEqual([x["case_id"] for x in db], ["3"])
        found = [{"date": "2026-10-24"}, {"date": "2026-08-25"}, {"date": None}]
        census.match_db(found, db)
        self.assertTrue(found[0]["in_db"])
        self.assertEqual(found[0]["db_case_id"], "3")
        self.assertFalse(found[1]["in_db"])
        self.assertFalse(found[2]["in_db"])


class TestGrade(unittest.TestCase):
    def rows(self):
        return [
            {"citation": "a", "date": "2026-10-21", "readable": True, "ai_mention": True,
             "ai_citation": True, "in_db": True, "other_body": True},
            {"citation": "b", "date": "2026-08-25", "readable": True, "ai_mention": True,
             "ai_citation": True, "in_db": False, "action": True},
            {"citation": "c", "date": "2025-01-02", "readable": True, "ai_mention": True,
             "ai_citation": True, "in_db": False},
            {"citation": "d", "date": "2022-05-01", "readable": True, "ai_citation": False},
            {"citation": "e", "date": "2023-05-01", "readable": False},
        ]

    def test_verdicts(self):
        res = census.grade(self.rows())
        v = {k: p["verdict"] for k, p in res["predictions"].items()}
        self.assertEqual(v, {"P1": "held", "P2": "held", "P3": "held", "P4": "failed",
                             "P5": "held", "P6": "held", "P7": "not testable"})
        self.assertEqual(res["counts"]["in_frame"], 5)
        self.assertEqual(res["counts"]["readable"], 4)
        self.assertEqual(res["counts"]["ai_citation"], 3)
        self.assertEqual(res["counts"]["by_year"]["2026"], {"readable": 2, "ai_mention": 2, "ai_citation": 2})

    def test_method_check_fails_on_early_hit(self):
        rows = self.rows()
        rows[3]["ai_citation"] = True
        self.assertEqual(census.grade(rows)["predictions"]["P5"]["verdict"], "failed")

    def test_small_n(self):
        res = census.grade(self.rows()[:1])
        self.assertEqual(res["predictions"]["P1"]["verdict"], "failed")
        self.assertEqual(res["predictions"]["P2"]["verdict"], "not testable")

    def test_outputs(self):
        rows = self.rows()
        res = census.grade(rows)
        for r in res["ai_citation_decisions"]:
            r["url"] = "https://www.flra.gov/decisions/v74/74-87"
        md = census.results_md(res, {"x": 1})
        self.assertIn("| P1 |", md)
        self.assertIn("](https://www.flra.gov/decisions/v74/74-87)", md)
        self.assertTrue(census.rows_csv(rows).startswith("citation,reporter_cite,date"))


